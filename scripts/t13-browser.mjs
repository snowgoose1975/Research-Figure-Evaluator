import { chromium } from "@playwright/test";
import { assertNewEvidence, evidenceFile, evidenceLabel, writeNewEvidence } from "./lib/evidence.mjs";
const label = evidenceLabel("T13-browser");
const base = process.env.RFE_APP_URL || "http://127.0.0.1:3001";
const files = { report: evidenceFile(label, ".json"), home: evidenceFile(label, "-home.png"), dialog: evidenceFile(label, "-dialog.png"), mobile: evidenceFile(label, "-mobile.png") };
assertNewEvidence(Object.values(files));
const checks = [], errors = [];
const browser = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on("pageerror", error => errors.push(error.message));
page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
const check = (name, pass) => { checks.push({ name, pass: Boolean(pass) }); if (!pass) throw new Error(name); };
const openDialog = () => page.getByRole("button", { name: /^View full-size:/ }).first().click();
const dialog = () => page.locator("dialog[open]");
const waitClosed = async () => { await page.waitForFunction(() => !document.querySelector("dialog[open]")); };
try {
  await page.goto(base, { waitUntil: "networkidle" });
  await page.getByRole("heading", { name: "Will readers understand your scientific figure?" }).waitFor();
  check("goal concerns the researcher's intended message and revision", /intended|expect/i.test(await page.locator("main").innerText()) && /revis/i.test(await page.locator("main").innerText()));
  await page.screenshot({ path: files.home, fullPage: true });
  const before = page.url();
  await openDialog();
  check("image opens inside the page with a clear close control", await dialog().count() === 1 && await dialog().getByRole("button", { name: "Close image", exact: true }).isVisible());
  check("no raw-image navigation or extra tab", page.url() === before && page.context().pages().length === 1);
  check("background scrolling is locked", await page.evaluate(() => document.body.style.overflow === "hidden"));
  await page.keyboard.press("Tab");
  check("keyboard focus remains in the modal", await page.evaluate(() => document.querySelector("dialog[open]").contains(document.activeElement)));
  await page.screenshot({ path: files.dialog });
  await dialog().getByRole("button", { name: "Close image", exact: true }).click();
  await waitClosed();
  check("close button restores trigger focus and scrolling", await page.evaluate(() => document.activeElement?.getAttribute("aria-haspopup") === "dialog" && document.body.style.overflow !== "hidden"));
  await openDialog(); await page.keyboard.press("Escape"); await waitClosed();
  check("Escape closes the image without leaving the page", page.url() === before);
  await openDialog(); await page.mouse.click(2, 2); await waitClosed();
  check("clicking the backdrop closes the image", await dialog().count() === 0);
  await page.goto(`${base}/?case=materials-lattice-design`, { waitUntil: "networkidle" });
  await page.getByRole("heading", { name: "Lattice topology to porous structure", exact: true }).waitFor();
  check("case images use the same in-page viewer", await page.getByRole("button", { name: /^View full-size:/ }).count() === 2);
  await page.setViewportSize({ width: 390, height: 844 });
  await openDialog();
  check("mobile close control stays visible", await dialog().getByRole("button", { name: "Close image", exact: true }).isVisible());
  check("mobile dialog fits the viewport", await dialog().evaluate(element => { const rect = element.getBoundingClientRect(); return rect.width <= innerWidth && rect.height <= innerHeight; }));
  await page.screenshot({ path: files.mobile });
  await page.keyboard.press("Escape"); await waitClosed();
  check("mobile returns to the same case", page.url().includes("case=materials-lattice-design"));
  check("no console or page errors", errors.length === 0);
} finally {
  writeNewEvidence(files.report, JSON.stringify({ label, base, checks, errors, scope: "Image modal, product wording and mobile browser validation; no model calls." }, null, 2) + "\n");
  await browser.close();
}
console.log(JSON.stringify({ label, checks, errors }, null, 2));
